create table posts (
    id             bigint generated by default as identity primary key,
    author_id      bigint       not null references users (id),
    title          varchar(100) not null,
    content        jsonb        not null,
    content_text   text         not null,
    game_patch     varchar(10)  not null,
    like_count     int          not null default 0,
    comment_count  int          not null default 0,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null
);

create index posts_created_idx on posts (created_at desc, id desc);
create index posts_likes_idx on posts (like_count desc, created_at desc, id desc);

create table post_champions (
    post_id      bigint      not null references posts (id) on delete cascade,
    champion_id  varchar(40) not null references champions (id),
    primary key (post_id, champion_id)
);

create index post_champions_champion_idx on post_champions (champion_id);

create table post_augments (
    post_id     bigint      not null references posts (id) on delete cascade,
    augment_id  varchar(80) not null references augments (id),
    primary key (post_id, augment_id)
);

create index post_augments_augment_idx on post_augments (augment_id);

create table images (
    id            uuid         primary key,
    uploader_id   bigint       not null references users (id),
    post_id       bigint       references posts (id) on delete set null,
    storage_key   varchar(200) not null,
    content_type  varchar(40)  not null,
    size_bytes    int          not null,
    created_at    timestamptz  not null
);

create index images_post_idx on images (post_id);
create index images_unlinked_idx on images (created_at) where post_id is null;
